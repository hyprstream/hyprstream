def ed25519_key(seed_byte: int):
    seed = bytes((seed_byte + i) & 0xFF for i in range(32))
    sk = Ed25519PrivateKey.from_private_bytes(seed)
    return seed, sk


class MlDsaKey:
    def __init__(self, seed: bytes, workdir: Path, name: str):
        self.seed = seed
        self.path = workdir / f"{name}.pem"
        subprocess.run(
            [
                "openssl",
                "genpkey",
                "-algorithm",
                "ML-DSA-65",
                "-pkeyopt",
                f"hexseed:{seed.hex()}",
                "-out",
                str(self.path),
            ],
            check=True,
            capture_output=True,
        )
        der = subprocess.run(
            ["openssl", "pkey", "-in", str(self.path), "-pubout", "-outform", "DER"],
            check=True,
            capture_output=True,
        ).stdout
        self.public = der[-1952:]

    def sign(self, message: bytes) -> bytes:
        with tempfile.NamedTemporaryFile(delete=False) as f:
            f.write(message)
            msg_path = f.name
        try:
            return subprocess.run(
                [
                    "openssl",
                    "pkeyutl",
                    "-sign",
                    "-inkey",
                    str(self.path),
                    "-rawin",
                    "-in",
                    msg_path,
                    "-pkeyopt",
                    "deterministic:1",
                ],
                check=True,
                capture_output=True,
            ).stdout
        finally:
            os.unlink(msg_path)


