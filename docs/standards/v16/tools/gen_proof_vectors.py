# --------------------------------------------------------------------------
# Deterministic CBOR (RFC 8949 §4.2.1 core deterministic encoding)
# --------------------------------------------------------------------------


class Raw:
    """Pre-encoded CBOR bytes, spliced in verbatim (used by negative vectors
    that deliberately violate deterministic encoding)."""

    def __init__(self, data: bytes):
        self.data = data


def _head(major: int, value: int) -> bytes:
    if value < 24:
        return bytes([(major << 5) | value])
    if value < 0x100:
        return bytes([(major << 5) | 24, value])
    if value < 0x10000:
        return bytes([(major << 5) | 25]) + value.to_bytes(2, "big")
    if value < 0x100000000:
        return bytes([(major << 5) | 26]) + value.to_bytes(4, "big")
    if value < 0x10000000000000000:
        return bytes([(major << 5) | 27]) + value.to_bytes(8, "big")
    raise ValueError("integer out of CBOR range")


def enc(obj) -> bytes:
    if isinstance(obj, Raw):
        return obj.data
    if obj is None:
        return b"\xf6"
    if obj is True:
        return b"\xf5"
    if obj is False:
        return b"\xf4"
    if isinstance(obj, int):
        if obj >= 0:
            return _head(0, obj)
        return _head(1, -1 - obj)
    if isinstance(obj, bytes):
        return _head(2, len(obj)) + obj
    if isinstance(obj, str):
        b = obj.encode("utf-8")
        return _head(3, len(b)) + b
    if isinstance(obj, list):
        out = _head(4, len(obj))
        for item in obj:
            out += enc(item)
        return out
    if isinstance(obj, dict):
        items = [(enc(k), enc(v)) for k, v in obj.items()]
        # Core deterministic encoding: map keys sorted bytewise-lexicographic
        # on their encoded form.
        items.sort(key=lambda kv: kv[0])
        out = _head(5, len(items))
        for k, v in items:
            out += k + v
        return out
    raise TypeError(f"unsupported type for deterministic CBOR: {type(obj)!r}")


def enc_unsorted(d: dict) -> bytes:
    """Encode a map in caller-declared order (deterministic-encoding
    violation used by a negative vector)."""
    out = _head(5, len(d))
    for k, v in d.items():
        out += enc(k) + enc(v)
    return out


def enc_indefinite_map(d: dict) -> bytes:
    out = b"\xbf"
    for k, v in d.items():
        out += enc(k) + enc(v)
    return out + b"\xff"


