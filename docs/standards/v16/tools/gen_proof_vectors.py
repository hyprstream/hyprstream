def component(alg: int, kid: bytes) -> dict:
    return {1: alg, 2: kid}


def group(group_id: int, suite: str, components: list) -> dict:
    return {1: group_id, 2: suite, 3: components}


def cose_key_okp_ed25519(kid: bytes, public: bytes) -> dict:
    # kty=OKP(1), kid(2), alg=Ed25519(-19), crv=Ed25519(6), x=public
    return {1: 1, 2: kid, 3: ALG_ED25519, -1: 6, -2: public}


def cose_key_akp_mldsa65(kid: bytes, public: bytes) -> dict:
    # kty=AKP(7), kid(2), alg=ML-DSA-65(-49), pub(-1)
    return {1: 7, 2: kid, 3: ALG_ML_DSA_65, -1: public}


def request_claims(
    *,
    credential_hash,
    nonce=None,
    response_binding=None,
    aud=SERVICE_DOMAIN,
    cti=REQUEST_ID,
    schema_id=SCHEMA_ID_REQUEST,
    body=CAPNP_REQUEST_BYTES,
    extra=None,
) -> dict:
    claims = {
        C_AUD: aud,
        C_EXP: EXP,
        C_IAT: IAT,
        C_CTI: cti,
        C_CREDENTIAL_HASH: credential_hash,
        C_SCHEMA_ID: schema_id,
        C_BODY_BYTES: body,
        C_RESPONSE_BINDING: response_binding,
    }
    if nonce is not None:
        claims[C_NONCE] = nonce
    if extra:
        claims.update(extra)
    return claims


def response_binding(kind: int, protection: int, kem=None) -> dict:
    # Frozen 4-key closed map (Gate-2 §19 #3/#4): root type id, orthogonal
    # response_kind and protection_mode axes, and the KEM recipient (non-null
    # iff protection_mode is encrypted).
    return {1: SCHEMA_ID_RESPONSE, 2: kind, 3: protection, 4: kem}


def kem_recipient() -> dict:
    # The alg slot carries the profile's frozen project-private ML-KEM-768
    # identifier -70200 (Gate-2 §19 #5). The exact value is REQUIRED.
    return {1: ALG_HS_KEM_ML_KEM_768, 2: ML_KEM_768_RECIPIENT, 3: b"service-mlkem768-1"}


def sig_structure_sign1(body_protected: bytes, payload: bytes) -> bytes:
    return enc(["Signature1", body_protected, EXTERNAL_AAD, payload])


def sig_structure_sign(
    body_protected: bytes, signer_protected: bytes, payload: bytes
) -> bytes:
    return enc(
        ["Signature", body_protected, signer_protected, EXTERNAL_AAD, payload]
    )


